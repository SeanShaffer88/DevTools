#!/usr/bin/env python3
"""build-ai-bundle.py - generate manifest.json and ai-bundle.md for
the DevTools Flutter pack.

Usage: python3 build-ai-bundle.py [flutter-pack-root]
       (default: the parent folder of this tools/ folder)

For AI tools (ChatGPT, Claude, any agent) that download the DevTools
repo and use this pack locally:

  * manifest.json - machine-readable map: purpose, reading order, and
    every file in the flutter/ folder with a one-line summary and size.
  * ai-bundle.md - the pack's guides and reference material
    concatenated into ONE markdown file, in reading order, so it can
    be uploaded or pasted as a single document. Code files (scripts,
    templates, fixtures, tools) are listed in the manifest instead of
    inlined.

Reading order: README.md, AGENTS.md, SOURCES.md (if present), guides/
in filename order, reference/, then the folder READMEs of scripts/,
templates/, fixtures/, tools/. Regenerate after any content change;
both outputs are stamped with the generation date.
Python 3, standard library only.
"""

import json
import os
import sys
from datetime import date

SKIP_DIRS = {".git", "__pycache__"}
ROOT_ORDER = ["README.md", "AGENTS.md", "SOURCES.md"]
DIR_ORDER = ["guides", "reference"]
README_ORDER = ["scripts", "templates", "fixtures", "tools"]
PURPOSE = ("DevTools Flutter Pack - Flutter development guides, "
           "scripts, templates, fixtures and tools")


def first_heading(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            for line in fh:
                line = line.strip()
                if line.startswith("#"):
                    return line.lstrip("# ").strip()
                if line:
                    return line[:100]
    except OSError:
        pass
    return ""


def collect(root):
    files = []
    for dirpath, dirs, names in os.walk(root):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for n in names:
            p = os.path.relpath(os.path.join(dirpath, n), root)
            files.append(p.replace(os.sep, "/"))
    return sorted(files)


def reading_order(files):
    ordered = []
    for name in ROOT_ORDER:
        if name in files:
            ordered.append(name)
    for d in DIR_ORDER:
        ordered += sorted(f for f in files
                          if f.startswith(d + "/") and f.endswith(".md"))
    for d in README_ORDER:
        if d + "/README.md" in files:
            ordered.append(d + "/README.md")
    return ordered


def main() -> int:
    if len(sys.argv) > 1:
        root = os.path.abspath(sys.argv[1])
    else:
        root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    files = collect(root)
    order = reading_order(files)

    manifest = {
        "repo": "devtools-flutter",
        "generated": date.today().isoformat(),
        "purpose": PURPOSE,
        "startHere": ["AGENTS.md", "README.md"],
        "readingOrder": order,
        "files": [
            {
                "path": f,
                "bytes": os.path.getsize(os.path.join(root, f)),
                "summary": first_heading(os.path.join(root, f))
                if f.endswith(".md") else "",
            }
            for f in files
            if f not in ("manifest.json", "ai-bundle.md")
        ],
    }
    with open(os.path.join(root, "manifest.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)

    bundle_path = os.path.join(root, "ai-bundle.md")
    with open(bundle_path, "w", encoding="utf-8") as out:
        out.write("# devtools-flutter - AI bundle\n\n")
        out.write(
            "The complete Flutter pack in one file, generated by "
            f"tools/build-ai-bundle.py on {date.today().isoformat()}. "
            "Generated file - edit the sources, not this bundle. "
            "Code files (scripts, tools, templates, fixtures) are not "
            "inlined; see manifest.json for the full file map. "
            "Relative links inside the bundle point at the original "
            "files in the pack - open the source file (named in the "
            "section markers) for working links.\n\n"
        )
        for rel in order:
            path = os.path.join(root, rel)
            if not rel.endswith(".md") or not os.path.exists(path):
                continue
            out.write(f"\n\n---\n\n<!-- ===== {rel} ===== -->\n\n")
            with open(path, encoding="utf-8", errors="replace") as fh:
                out.write(fh.read())
    print(f"manifest.json: {len(manifest['files'])} files")
    print(f"ai-bundle.md: {os.path.getsize(bundle_path)} bytes, "
          f"{len(order)} documents in reading order")
    return 0


if __name__ == "__main__":
    sys.exit(main())
